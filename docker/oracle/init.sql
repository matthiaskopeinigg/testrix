ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER SESSION SET CURRENT_SCHEMA = testrix;

CREATE TABLE IF NOT EXISTS testrix.categories (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(64) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS testrix.customers (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR2(128) NOT NULL UNIQUE,
  name VARCHAR2(128) NOT NULL
);

CREATE TABLE IF NOT EXISTS testrix.sample_items (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(64) NOT NULL,
  category_id NUMBER NOT NULL REFERENCES testrix.categories (id),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS testrix.orders (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id NUMBER NOT NULL REFERENCES testrix.customers (id),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS testrix.order_items (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id NUMBER NOT NULL REFERENCES testrix.orders (id),
  sample_item_id NUMBER NOT NULL REFERENCES testrix.sample_items (id),
  qty NUMBER NOT NULL
);

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX sample_items_name_idx ON testrix.sample_items (name)';
