BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX customers_email_idx ON testrix.customers (email)';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE NOT IN (-955, -1408) THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX orders_created_at_idx ON testrix.orders (created_at)';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE NOT IN (-955, -1408) THEN RAISE; END IF;
END;
/

CREATE OR REPLACE VIEW testrix.order_summaries AS
SELECT o.id AS order_id, c.name AS customer_name, COUNT(oi.id) AS item_count
FROM testrix.orders o
JOIN testrix.customers c ON c.id = o.customer_id
LEFT JOIN testrix.order_items oi ON oi.order_id = o.id
GROUP BY o.id, c.name;

CREATE OR REPLACE FUNCTION testrix.item_count(p_order_id NUMBER)
RETURN NUMBER
IS
  v_count NUMBER;
BEGIN
  SELECT COALESCE(SUM(qty), 0) INTO v_count FROM testrix.order_items WHERE order_id = p_order_id;
  RETURN v_count;
END;
/

CREATE OR REPLACE TRIGGER testrix.sample_items_set_updated_at
BEFORE UPDATE ON testrix.sample_items
FOR EACH ROW
BEGIN
  :NEW.updated_at := SYSTIMESTAMP;
END;
/

